export const JAKARTA_HUB_GEO: CountryGeoNode = RAW_COUNTRY_COORDS.INDONESIA;

export function resolveCountryGeo(rawName: string): CountryGeoNode {
  const key = rawName.trim().toUpperCase();
  if (RAW_COUNTRY_COORDS[key]) {
    return RAW_COUNTRY_COORDS[key];
  }
  const partial = Object.entries(RAW_COUNTRY_COORDS).find(
    ([k, v]) => key.includes(k) || key === v.code
  );
  if (partial) {
    return partial[1];
  }
  return {
    id: key.substring(0, 2) || 'GL',
    name: rawName.trim(),
    code: key.substring(0, 2) || 'GL',
    lat: 15,
    lon: 30,
    region: 'Internasional',
  };
}
